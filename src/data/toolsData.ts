// Pixel-art "item" icons for the Tools of the Trade inventory. Each tool is
// a 10x10 bitmap (row strings) plus a character→color lookup for PixelIcon;
// '.' is transparent. Shapes are simplified, brand-colored silhouettes
// (ring, chevron, hexagon, etc.) rather than literal logos, so they stay
// legible at tiny inventory-slot sizes.
//
// Tools with a `spriteKey` use the real pixel-art icon sprite sheet
// (public/assets/ui/tech-stack.png, see the `.tech-icon--*` CSS classes)
// instead of the bitmap fallback — everything else keeps the hand-drawn
// PixelIcon badge since the pack doesn't ship art for it yet.
export interface ToolIcon {
  name: string;
  rows: string[];
  colors: Record<string, string>;
  spriteKey?: string;
}

